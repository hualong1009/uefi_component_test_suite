#!/usr/bin/env python3
"""Generate the UI translation dictionary from tools/i18n.tsv.

The TSV holds one entry per line:  <source Chinese><TAB><English>
Lines starting with '#' are comments, empty lines are ignored.

The C sources are written in Chinese and every user visible string goes
through L(); the dictionary supplies the English form. This script also
reports source strings that have no translation yet, so new UI text cannot
silently stay Chinese in English mode.

    python tools/geni18n.py            # regenerate src/generated/i18n_data.c
    python tools/geni18n.py --check    # only report missing translations
    python tools/geni18n.py --stub     # add empty entries for missing strings
"""
import argparse
import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TSV = os.path.join(ROOT, "tools", "i18n.tsv")
OUT = os.path.join(ROOT, "src", "generated", "i18n_data.c")

LITERAL = re.compile(r'"((?:[^"\\]|\\.)*)"')
# Han characters plus CJK punctuation, fullwidth forms and arrows: any string
# containing one of them is user visible text and needs a translation.
NEEDS_TEXT = re.compile(u'[\u4e00-\u9fff\u3000-\u303f\uff01-\uff60\u2014\u2018-\u201d\u2190-\u21ff\u2500-\u257f]')


def unescape(text):
    out = []
    i = 0
    while i < len(text):
        ch = text[i]
        if ch == chr(92) and i + 1 < len(text):
            nxt = text[i + 1]
            if nxt == chr(92):
                out.append(chr(92))
                i += 2
                continue
            if nxt == 'n':
                out.append(chr(10))
                i += 2
                continue
            if nxt == 't':
                out.append(chr(9))
                i += 2
                continue
            if nxt == '"':
                out.append('"')
                i += 2
                continue
        out.append(ch)
        i += 1
    return "".join(out)


def load_tsv(path):
    entries = []
    seen = set()
    if not os.path.exists(path):
        return entries
    with open(path, encoding="utf-8") as fh:
        for lineno, line in enumerate(fh, 1):
            line = line.rstrip("\n").rstrip("\r")
            if not line or line.lstrip().startswith("#"):
                continue
            if "\t" not in line:
                print("i18n.tsv:%d: expected <zh>TAB<en>" % lineno, file=sys.stderr)
                continue
            zh, en = line.split("\t", 1)
            zh = unescape(zh)
            # leading/trailing spaces are meaningful in fragments such as
            # " · primary CPU", so the English text is kept verbatim
            en = unescape(en.rstrip("\r\n"))
            if not zh.strip() or zh in seen:
                continue
            seen.add(zh)
            entries.append((zh, en))
    return entries


def source_strings():
    """Every string literal that reaches the runtime, with adjacent literals
    merged the way the C compiler concatenates them ("a" "b" -> "ab")."""
    strings = set()
    for path in sorted(glob.glob(os.path.join(ROOT, "src", "*.c"))):
        if path.endswith("i18n.c"):
            continue
        text = open(path, encoding="utf-8").read()
        merged = []
        last_end = -1
        for match in LITERAL.finditer(text):
            gap = text[last_end:match.start()] if last_end >= 0 else None
            if merged and gap is not None and gap.strip() == "":
                merged[-1] += match.group(1)
            else:
                merged.append(match.group(1))
            last_end = match.end()
        for value in merged:
            value = unescape(value)
            if NEEDS_TEXT.search(value):
                strings.add(value)
    return strings


def escape_tsv(s):
    out = []
    for ch in s:
        if ch == chr(92):
            out.append(chr(92) + chr(92))
        elif ch == chr(10):
            out.append(chr(92) + "n")
        elif ch == chr(9):
            out.append(chr(92) + "t")
        else:
            out.append(ch)
    return "".join(out)


def c_escape(s):
    out = []
    for ch in s:
        if ch == '"':
            out.append(chr(92) + '"')
        elif ch == chr(92):
            out.append(chr(92) + chr(92))
        elif ch == chr(10):
            out.append(chr(92) + "n")
        elif ch == chr(9):
            out.append(chr(92) + "t")
        else:
            out.append(ch)
    return "".join(out)


def emit(entries, path):
    entries = sorted(entries, key=lambda e: e[0])
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("/* i18n_data.c - generated by tools/geni18n.py, do not edit. */\n")
        fh.write('#include "uefi.h"\n\n')
        fh.write("const unsigned int gI18nCount = %d;\n\n" % len(entries))
        fh.write("const char *const gI18nZh[%d] = {\n" % max(1, len(entries)))
        for zh, _ in entries:
            fh.write('  "%s",\n' % c_escape(zh))
        if not entries:
            fh.write('  "",\n')
        fh.write("};\n\n")
        fh.write("const char *const gI18nEn[%d] = {\n" % max(1, len(entries)))
        for zh, en in entries:
            fh.write('  "%s",\n' % c_escape(en if en else zh))
        if not entries:
            fh.write('  "",\n')
        fh.write("};\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--stub", action="store_true")
    args = ap.parse_args()

    entries = load_tsv(TSV)
    have = {zh for zh, _ in entries}
    missing = sorted(s for s in source_strings() if s not in have)

    if args.stub and missing:
        with open(TSV, "a", encoding="utf-8", newline="\n") as fh:
            for s in missing:
                fh.write("%s\t\n" % s)
        print("added %d stub entries to tools/i18n.tsv" % len(missing))
        entries = load_tsv(TSV)
        missing = []

    untranslated = [zh for zh, en in entries if not en]
    if missing:
        print("i18n: %d source strings without a dictionary entry:" % len(missing))
        for s in missing[:20]:
            print("  " + s)
        if len(missing) > 20:
            print("  ...")
    if untranslated:
        print("i18n: %d entries have an empty English text" % len(untranslated))

    if args.check:
        return 0

    emit(entries, OUT)
    print("i18n: %d entries -> %s" % (len(entries), os.path.relpath(OUT, ROOT)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
