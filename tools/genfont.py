#!/usr/bin/env python3
"""Generate the bitmap fonts used by UCTS.

Scans the C sources for the CJK characters actually used, rasterises them
together with a Latin glyph set, and emits a single C file with 8-bit
anti-aliased coverage bitmaps (blended at draw time).

    python tools/genfont.py            # regenerate src/generated/font_data.c
    python tools/genfont.py --sheet    # also write a preview PNG

Fonts are resolved from the Windows font directory, so the generated file is
committed and normal builds never need this script.
"""
import argparse
import glob
import os
import sys

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

LATIN_W, LATIN_H = 8, 16
CJK_W, CJK_H = 16, 16
LATIN_FONT = "consola.ttf"     # Consolas: crisp at 8x16
CJK_FONT = "Deng.ttf"          # DengXian: clean sans CJK at 16 px

# Characters always included even if they are not (yet) referenced in code.
ALWAYS = (
    "".join(chr(c) for c in range(0x20, 0x7F))
    + "·—…‘’“”（）《》、，。！？：；【】％℃×→←↑↓●○■□▲▼✓✗µΩ"
)

# Substitution strings for Latin-only fallback rendering of box drawing.
CJK_SCAN_EXTS = (".c", ".h")


def find_font(name):
    candidates = [
        os.path.join(os.environ.get("WINDIR", r"C:\Windows"), "Fonts", name),
        os.path.join(ROOT, "tools", "fonts", name),
        "/usr/share/fonts/truetype/" + name,
    ]
    for c in candidates:
        if os.path.exists(c):
            return c
    raise SystemExit("font not found: %s" % name)


def collect_chars():
    chars = set(ALWAYS)
    for path in glob.glob(os.path.join(ROOT, "src", "**", "*.*"), recursive=True):
        if not path.endswith(CJK_SCAN_EXTS):
            continue
        with open(path, "r", encoding="utf-8", errors="replace") as fh:
            for ch in fh.read():
                if ord(ch) > 0x7F:
                    chars.add(ch)
    return sorted(chars, key=ord)


def render_char(ch, path, w, h, size, cjk=False):
    """Rasterise one character into a w*h 8-bit coverage cell.

    The glyph is drawn at 4x supersampling, then area-filtered down.  Latin
    cells share one baseline row (h - 4) and the pen sits at x = 0 so that the
    run-time advance (derived from the ink extents) stays proportional.  The
    baseline must come from the font metrics, not from each glyph's ink box:
    aligning by ink box lifts every descender ('p', 'g', 'y') up by its
    descender depth and the letters then read as 'P', 'G', 'Y'.
    CJK cells are centred in the square cell.
    """
    ss = 4
    font = ImageFont.truetype(path, size * ss)
    img = Image.new("L", (w * ss, h * ss), 0)
    draw = ImageDraw.Draw(img)
    bbox = draw.textbbox((0, 0), ch, font=font)
    gw = bbox[2] - bbox[0]
    gh = bbox[3] - bbox[1]
    if gw > 0 and gh > 0:
        if cjk:
            x = (w * ss - gw) // 2 - bbox[0]
            y = (h * ss - gh) // 2 - bbox[1]
        else:
            ascent, _descent = font.getmetrics()
            x = -bbox[0] + ss
            y = (h - 4) * ss - ascent
        draw.text((x, y), ch, fill=255, font=font)
    return img.resize((w, h), Image.LANCZOS).tobytes()


def emit(path_out, latin, cjk_chars, cjk):
    lines = []
    add = lines.append
    add("/* Auto generated by tools/genfont.py - do not edit. */")
    add('#include "font.h"')
    add("")
    add("const unsigned int gFontLatinCount = %d;" % len(latin))
    add("const unsigned char gFontLatinData[%d][%d] = {" % (len(latin), LATIN_W * LATIN_H))
    for idx, data in enumerate(latin):
        vals = ",".join(str(b) for b in data)
        add("  { %s }, /* 0x%02X */" % (vals, 0x20 + idx))
    add("};")
    add("")
    add("const unsigned int gFontCjkCount = %d;" % len(cjk_chars))
    add("const unsigned short gFontCjkCodes[%d] = {" % len(cjk_chars))
    row = []
    for ch in cjk_chars:
        row.append("0x%04X" % ord(ch))
        if len(row) == 12:
            add("  " + ",".join(row) + ",")
            row = []
    if row:
        add("  " + ",".join(row) + ",")
    add("};")
    add("")
    add("const unsigned char gFontCjkData[%d][%d] = {" % (len(cjk_chars), CJK_W * CJK_H))
    for ch, data in zip(cjk_chars, cjk):
        vals = ",".join(str(b) for b in data)
        add("  { %s }, /* %s U+%04X */" % (vals, ch, ord(ch)))
    add("};")
    add("")
    os.makedirs(os.path.dirname(path_out), exist_ok=True)
    with open(path_out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))


def write_sheet(path, latin_src, cjk_chars, cjk_data):
    cols = 32
    rows = (len(cjk_data) + cols - 1) // cols
    img = Image.new("RGB", (cols * (CJK_W + 4), rows * (CJK_H + 4) + 40), (255, 255, 255))
    draw = ImageDraw.Draw(img)
    for i, (ch, data) in enumerate(zip(cjk_chars, cjk_data)):
        cx = (i % cols) * (CJK_W + 4)
        cy = (i // cols) * (CJK_H + 4)
        tile = Image.frombytes("L", (CJK_W, CJK_H), bytes(data))
        img.paste(Image.merge("RGB", (tile, tile, tile)), (cx, cy))
    latin = Image.new("RGB", (95 * (LATIN_W + 2), LATIN_H + 4), (255, 255, 255))
    for i in range(95):
        tile = Image.frombytes("L", (LATIN_W, LATIN_H), bytes(latin_src[i]))
        latin.paste(Image.merge("RGB", (tile, tile, tile)), (i * (LATIN_W + 2), 0))
    img.paste(latin, (0, rows * (CJK_H + 4)))
    img.save(path)
    print("sheet ->", path)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(ROOT, "src", "generated", "font_data.c"))
    ap.add_argument("--sheet", default=None)
    args = ap.parse_args()

    latin_path = find_font(LATIN_FONT)
    cjk_path = find_font(CJK_FONT)
    latin = [render_char(chr(0x20 + i), latin_path, LATIN_W, LATIN_H, 13) for i in range(95)]
    chars = collect_chars()
    cjk = [render_char(ch, cjk_path, CJK_W, CJK_H, 15, cjk=True) for ch in chars]
    emit(args.out, latin, chars, cjk)
    print("latin glyphs: %d, cjk glyphs: %d -> %s" % (len(latin), len(chars), args.out))
    if args.sheet:
        write_sheet(args.sheet, latin, chars, cjk)


if __name__ == "__main__":
    main()
